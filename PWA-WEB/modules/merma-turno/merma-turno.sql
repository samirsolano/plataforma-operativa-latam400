-- Reemplaza el Excel "F-LAT-012 REPORTE DE MERMA POR TURNO":
--   - merma_mara: maestro de materiales con su UBICACIÓN DE PICKING
--     (hoja MARA + hoja BASES del Excel). Se actualiza desde el
--     módulo (pestaña MARA Merma).
--   - merma_motivos: catálogo de motivos (código A1..D7 → origen y
--     clasificación de daño). Corregido respecto al Excel: "PALLET EN
--     MAL ESTADO" es D1 (en la hoja REGISTRO estaba repetido como A6).
--   - merma_registros: lo que registra el auxiliar en Centro de
--     Proyectos (una fila por línea), con su DNI. Al hacer el cambio
--     en la ubicación, estado pasa de PENDIENTE a HECHO.
--   - merma_cruces + merma_sap: cada vez que se pega el stock físico
--     de SAP (una "unidad de manipulación", p. ej. MERMAPENDI30.10) se
--     crea un cruce con sus líneas de SAP. Cruce 1 = Registro vs SAP.
--   - merma_validacion: conteo físico ciego por cruce. Cruce final =
--     Físico vs SAP.

create table if not exists public.merma_mara (

    codigo text primary key,
    ean14 text,
    ean13 text,
    descripcion text,
    unidad_venta text,
    unidad_base text,
    conversion numeric,
    ubicacion_picking text,
    marca text,
    categoria text,
    base text not null default 'REGULAR',

    actualizado_por text,
    updated_at timestamptz not null default now()

);

create index if not exists merma_mara_ean14_idx on public.merma_mara (ean14);
create index if not exists merma_mara_ean13_idx on public.merma_mara (ean13);

create table if not exists public.merma_motivos (

    codigo text primary key,
    motivo text not null,
    origen text not null,
    clasificacion text not null,
    activo boolean not null default true

);

