create table if not exists public.merma_registros (

    id bigint generated by default as identity primary key,

    -- Agrupa las líneas que el auxiliar registró juntas con un solo
    -- clic en REGISTRAR (CP-AAAAMMDD-HHMMSS-DNI).
    registro_id text not null,
    linea int not null,
    area text not null default 'CENTRO DE PROYECTO',

    dni text not null,
    nombre text,
    turno text,
    grupo text,
    fecha date not null,
    hora text,

    codigo text not null,
    ean text,
    descripcion text,
    ubicacion text,
    uma text,
    base text,
    marca text,
    categoria text,
    cantidad numeric not null check (cantidad > 0),

    motivo_codigo text,
    motivo text,
    origen text,
    clasificacion text,
    -- OK / REVISAR (regla de la columna M de la hoja REGISTRO).
    validacion text,
    proceso text not null default 'OUT',

    -- PENDIENTE hasta que el auxiliar hace el cambio en la ubicación.
    estado text not null default 'PENDIENTE',
    cambio_at timestamptz,

    created_at timestamptz not null default now(),

    unique (registro_id, linea)

);

create index if not exists merma_registros_fecha_idx on public.merma_registros (fecha, grupo);
create index if not exists merma_registros_dni_idx on public.merma_registros (dni, estado);

create table if not exists public.merma_cruces (

    id bigint generated by default as identity primary key,

    -- "Unidad manipulación" de SAP, p. ej. MERMAPENDI30.10 o
    -- MERMAJQ04.11 (MERMA + grupo + dd.mm).
    unidad_manipulacion text not null unique,
    grupo text,
    fecha date,

    -- Qué registros de merma entran en el cruce.
    desde date,
    hasta date,
    grupo_filtro text not null default '',

    cargado_por text,
    created_at timestamptz not null default now()

);

create table if not exists public.merma_sap (

    id bigint generated by default as identity primary key,
    cruce_id bigint not null references public.merma_cruces (id) on delete cascade,

    producto text not null,
    descripcion text,
    lote text,
    fecha_caducidad text,
    tipo_stock text,
    ctd_embalada numeric,
    unidad_medida text,
    unidad_manipulacion text,
    -- Cantidad tal como sale en SAP (unidad base) y convertida a la
    -- UMA del maestro, que es en lo que registra el auxiliar.
    ctd numeric,
    ctd_uma numeric

);

create index if not exists merma_sap_cruce_idx on public.merma_sap (cruce_id);

create table if not exists public.merma_validacion (

    id bigint generated by default as identity primary key,
    cruce_id bigint not null references public.merma_cruces (id) on delete cascade,

    codigo text not null,
    ean text,
    descripcion text,
    uma text,
    cantidad numeric not null check (cantidad > 0),

    usuario text,
    created_at timestamptz not null default now()

);

create index if not exists merma_validacion_cruce_idx on public.merma_validacion (cruce_id);

-- ========================================
-- RLS — mismo criterio que el resto del proyecto: la app usa la
-- clave pública (anon) del cliente para todo, sin login propio de
-- Supabase, así que las políticas quedan abiertas a "anon".
-- ========================================

do $$
declare
    t text;
begin
    foreach t in array array['merma_mara','merma_motivos','merma_registros','merma_cruces','merma_sap','merma_validacion'] loop
        execute format('alter table public.%I enable row level security', t);
        execute format('drop policy if exists %I on public.%I', t || '_select_anon', t);
        execute format('drop policy if exists %I on public.%I', t || '_insert_anon', t);
        execute format('drop policy if exists %I on public.%I', t || '_update_anon', t);
        execute format('drop policy if exists %I on public.%I', t || '_delete_anon', t);
        execute format('create policy %I on public.%I for select to anon using (true)', t || '_select_anon', t);
        execute format('create policy %I on public.%I for insert to anon with check (true)', t || '_insert_anon', t);
        execute format('create policy %I on public.%I for update to anon using (true) with check (true)', t || '_update_anon', t);
        execute format('create policy %I on public.%I for delete to anon using (true)', t || '_delete_anon', t);
    end loop;
end $$;
