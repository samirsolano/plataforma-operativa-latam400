-- ========================================
-- MÓDULO "PROYECTO MIGRACIÓN DE DRIVE" — tablas de Facturación ›
-- Cargar Viaje. Corre esto UNA VEZ en el SQL Editor del proyecto
-- Supabase PRINCIPAL de la plataforma (rmlilqdhxbhpwkysucaz).
-- Se puede volver a correr sin romper nada (todo es "if not exists" /
-- "or replace").
-- ========================================
-- De dónde sale cada dato (archivos de SAP):
--   Monitor GRE: Entrega, Orden de flete (FO), Código y Nombre
--     Transportista. Una fila por entrega; un viaje (FO) tiene varias
--     entregas (en la muestra, hasta 34) y un solo transportista.
--   VL06F (Programaciones): una fila por MATERIAL de cada entrega
--     (Entrega, Material, Cantidad, Peso total en KG, Destinatario,
--     Lugar, Solicitante, Organización ventas, Ruta...). Destinatario,
--     Lugar, Ruta, etc. son siempre los mismos dentro de una entrega.
--
-- Estructura:
--   md_viajes   → una fila por viaje (FO). Es la "Base de Datos" contra
--                 la que se hace el Cruce de Viajes.
--   md_entregas → una fila por entrega de cada viaje, con los datos del
--                 VL06F ya SUMADOS por entrega (peso, cantidades).
--   md_cruces   → historial de cada vez que se pegan viajes (reemplaza
--                 el "Ver último cruce" guardado en el navegador).
--   md_rutas_gestion → qué gestión (Canal Moderno / Reparto Local /
--                 Larga Distancia) corresponde a cada ruta de SAP.
--
-- PENSADO PARA CRECER:
--   * El detalle por material del VL06F NO se guarda (en la muestra
--     son ~45 líneas por viaje: a 200 viajes/día serían ~3 millones de
--     filas al año). Se guarda sumado por entrega, que es lo que usan
--     las pantallas. Si algún día hace falta el detalle por material,
--     se agrega una tabla aparte.
--   * El cruce NO descarga la tabla: la función md_viajes_existentes
--     recibe solo los viajes pegados y devuelve cuáles ya existen
--     (usa la llave primaria, es inmediato aunque haya millones).
--   * Índices por fecha de carga, gestión y estado: por ahí filtran
--     Base de Datos y Reportes (siempre por rango de fechas y
--     paginado, nunca la tabla completa).

-- ========================================
-- RUTA → GESTIÓN
-- ========================================
-- La gestión no viene en ningún archivo de SAP. Se arma una sola vez
-- por ruta (la Ruta es la misma en todas las entregas de un viaje).
-- Rutas vistas en la muestra: 1054A1, 1054A3, 1054A4, 1054D1, 1054D2,
-- 1054D4. Se cargan desde la plataforma (o a mano acá) cuando se
-- confirme a qué gestión va cada una; una ruta sin fila deja el viaje
-- con gestión vacía ("SIN GESTIÓN") para asignarla a mano.

create table if not exists public.md_rutas_gestion (

    ruta text primary key,
    gestion text not null
        check (gestion in ('CANAL MODERNO', 'REPARTO LOCAL', 'LARGA DISTANCIA')),
    descripcion text,
    actualizado_en timestamptz not null default now()

);

-- ========================================
-- CRUCES (historial de "Pegar viajes de SAP" → "Cruzar viajes")
-- ========================================

create table if not exists public.md_cruces (

    id bigint generated by default as identity primary key,
    creado_en timestamptz not null default now(),
    usuario text,

    total_pegados integer not null,
    total_nuevos integer not null,
    viajes_nuevos text[] not null default '{}'

);

create index if not exists idx_md_cruces_creado_en
    on public.md_cruces (creado_en desc);

-- ========================================
-- VIAJES (uno por FO)
-- ========================================

create table if not exists public.md_viajes (

    fo text primary key,

    -- Cuándo y desde qué cruce entró a la base
    fecha_carga timestamptz not null default now(),
    cruce_id bigint references public.md_cruces (id) on delete set null,
    cargado_por text,

    -- Monitor GRE
    transportista_codigo text,
    transportista_nombre text,

    -- VL06F (resumen del viaje, calculado de sus entregas)
    ruta text,
    gestion text
        check (gestion in ('CANAL MODERNO', 'REPARTO LOCAL', 'LARGA DISTANCIA')),
    destino text,
    cliente text,
    peso_tn numeric(12, 3),
    cantidad_entregas integer,

    -- NUEVO: recién cruzado, falta Monitor GRE / VL06F
    -- PROCESADO: ya tiene sus datos (aparece en la tabla por gestión)
    -- SUBIDO: ya se subió / procesó desde Cargar Viaje
    estado text not null default 'NUEVO'
        check (estado in ('NUEVO', 'PROCESADO', 'SUBIDO')),

    actualizado_en timestamptz not null default now()

);

create index if not exists idx_md_viajes_fecha_carga
    on public.md_viajes (fecha_carga desc);

create index if not exists idx_md_viajes_gestion_fecha
    on public.md_viajes (gestion, fecha_carga desc);

create index if not exists idx_md_viajes_estado
    on public.md_viajes (estado, fecha_carga desc);

-- ========================================
-- ENTREGAS (varias por viaje)
-- ========================================

create table if not exists public.md_entregas (

    entrega text primary key,
    fo text not null references public.md_viajes (fo) on delete cascade,

    -- VL06F (iguales en todas las líneas de la entrega)
    documento_modelo text,
    destinatario_codigo text,
    destinatario_nombre text,
    lugar_destinatario text,
    solicitante text,
    organizacion_ventas text,
    ruta text,

    -- VL06F sumado por entrega (Peso total viene en KG)
    peso_kg numeric(12, 3),
    cantidad_lineas integer,
    cantidad_cja numeric(12, 3),
    cantidad_pqt numeric(12, 3),
    cantidad_und numeric(12, 3),

    -- Una entrega del Monitor GRE que todavía no aparece en el VL06F
    -- se guarda igual, con estos campos vacíos (en la muestra: 6 de 250).
    tiene_vl06f boolean not null default false,

    actualizado_en timestamptz not null default now()

);

create index if not exists idx_md_entregas_fo
    on public.md_entregas (fo);

-- ========================================
-- FUNCIÓN DEL CRUCE: ¿cuáles de estos viajes ya existen?
-- ========================================
-- La pantalla manda solo los viajes pegados (ej. 200) y recibe los que
-- ya están en md_viajes. Nunca se descarga la tabla completa.

create or replace function public.md_viajes_existentes(p_viajes text[])
returns setof text
language sql
stable
as $$
    select v.fo
    from public.md_viajes v
    where v.fo = any (p_viajes);
$$;

grant execute on function public.md_viajes_existentes(text[]) to anon;

-- ========================================
-- PERMISOS — mismo criterio que el resto de la plataforma (permisos_rol,
-- roles_app): RLS + policies para "anon". El control de quién entra lo
-- hace la plataforma (el módulo es solo para Administrador).
-- ========================================

alter table public.md_rutas_gestion enable row level security;
alter table public.md_cruces enable row level security;
alter table public.md_viajes enable row level security;
alter table public.md_entregas enable row level security;

drop policy if exists "md_rutas_gestion_anon" on public.md_rutas_gestion;
drop policy if exists "md_cruces_anon" on public.md_cruces;
drop policy if exists "md_viajes_anon" on public.md_viajes;
drop policy if exists "md_entregas_anon" on public.md_entregas;

create policy "md_rutas_gestion_anon" on public.md_rutas_gestion for all to anon using (true) with check (true);
create policy "md_cruces_anon" on public.md_cruces for all to anon using (true) with check (true);
create policy "md_viajes_anon" on public.md_viajes for all to anon using (true) with check (true);
create policy "md_entregas_anon" on public.md_entregas for all to anon using (true) with check (true);
