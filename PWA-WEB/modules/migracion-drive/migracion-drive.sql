-- ========================================
-- LÍNEAS DE VIAJE (Tottus)
-- ========================================
-- Un viaje de Tottus se sube partido por NEGOCIO × RÓTULO, como en el
-- Drive (ej. 1000181352: ALICORP LIMPIEZA T.HUACHIPA / ALICORP LIMPIEZA
-- T.LIMPIEZA / INTRADEVCO T.LIMPIEZA / INTRADEVCO TOTTUS ORIENTE).
-- Status Pendiente y el Monitor muestran una fila por línea; cada una
-- lleva su fase, canales y status. El status del viaje queda como el de
-- su línea más atrasada.

create table if not exists public.md_viaje_lineas (
    id bigint generated by default as identity primary key,
    fo text not null references public.md_viajes (fo) on delete cascade,
    linea integer not null,
    cliente text not null,
    rotulo text not null,
    peso_kg numeric(12, 3) not null default 0,
    fase text,
    canal_sistema text,
    canal_fisico text,
    status text,
    monitor_por text,
    monitor_en timestamptz,
    actualizado_en timestamptz not null default now(),
    unique (fo, linea)
);

create index if not exists idx_md_viaje_lineas_fo on public.md_viaje_lineas (fo);

alter table public.md_viaje_lineas enable row level security;
drop policy if exists "md_viaje_lineas_anon" on public.md_viaje_lineas;
create policy "md_viaje_lineas_anon" on public.md_viaje_lineas for all to anon using (true) with check (true);

-- ========================================
-- FUNCIÓN DEL CRUCE: ¿cuáles de estos viajes ya existen?
-- ========================================
-- La pantalla manda solo los viajes pegados (ej. 200) y recibe los que
-- ya están subidos en md_viajes. Nunca se descarga la tabla completa. Solo
-- cuentan como existentes los SUBIDO: un viaje cruzado o procesado
-- que no se llegó a subir vuelve a salir como nuevo en el siguiente
-- cruce (y los PENDIENTE, para completarlos con un VL06F que traiga
-- las entregas que faltaban).

create or replace function public.md_viajes_existentes(p_viajes text[])
returns setof text
language sql
stable
as $$
    select v.fo
    from public.md_viajes v
    where v.fo = any (p_viajes)
      and v.estado = 'SUBIDO';
$$;

grant execute on function public.md_viajes_existentes(text[]) to anon;

