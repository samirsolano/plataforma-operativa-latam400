-- ========================================
-- VIAJES (uno por FO)
-- ========================================

create table if not exists public.md_viajes (

    fo text primary key,

    -- fecha_carga: primer cruce (cuándo entró a la base)
    -- fecha_cruce / cruzado_por: último cruce en que salió como nuevo
    -- cargado_por: quién lo procesó
    fecha_carga timestamptz not null default now(),
    fecha_cruce timestamptz,
    cruzado_por text,
    cargado_por text,

    -- Monitor GRE
    transportista_codigo text,
    transportista_nombre text,

    -- VL06F (resumen del viaje, calculado de sus entregas)
    ruta text,
    -- CANAL MODERNO, RL CMP, RL AS, N/S CHICO, TRASLADO, DEX, LARGA
    -- DISTANCIA... (ver md_reglas_gestion; sin lista fija para que una
    -- gestión nueva no obligue a cambiar la tabla)
    gestion text,
    -- PROCESAR ("Procesar viaje") o SUBIR ("Subir viaje"), ver
    -- md_reglas_gestion
    accion text not null default 'SUBIR'
        check (accion in ('PROCESAR', 'SUBIR')),
    destino text,
    cliente text,
    peso_tn numeric(12, 3),
    cantidad_entregas integer,
    -- Materiales distintos del viaje en el VL06F
    cantidad_skus integer,

    -- NUEVO: cruzado, todavía no procesado (falta Monitor GRE / VL06F)
    -- PENDIENTE: procesado, pero alguna entrega no estaba en el VL06F
    --            (sin peso/destino). Vuelve a salir como nuevo en el
    --            siguiente cruce para completarlo.
    -- PROCESADO: ya tiene todos sus datos (si no se sube, también
    --            vuelve a salir como nuevo en el siguiente cruce)
    -- SUBIDO: ya se subió / procesó desde Cargar Viaje. Es lo único
    --         contra lo que cruza md_viajes_existentes.
    estado text not null default 'NUEVO',

    actualizado_en timestamptz not null default now()

);

