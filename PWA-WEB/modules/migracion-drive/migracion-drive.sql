-- ========================================
-- FUNCIÓN DEL CRUCE: ¿cuáles de estos viajes ya existen?
-- ========================================
-- La pantalla manda solo los viajes pegados (ej. 200) y recibe los que
-- ya están subidos en md_viajes. Nunca se descarga la tabla completa. Solo
-- cuentan como existentes los SUBIDO: un viaje cruzado o procesado
-- que no se llegó a subir vuelve a salir como nuevo en el siguiente
-- cruce (y los PENDIENTE, para completarlos con un VL06F que traiga
-- las entregas que faltaban).

create or replace function public.md_viajes_existentes(p_viajes text[])
returns setof text
language sql
stable
as $$
    select v.fo
    from public.md_viajes v
    where v.fo = any (p_viajes)
      and v.estado = 'SUBIDO';
$$;

grant execute on function public.md_viajes_existentes(text[]) to anon;

