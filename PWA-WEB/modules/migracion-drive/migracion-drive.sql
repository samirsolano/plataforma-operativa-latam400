-- ========================================
-- VIAJES (uno por FO)
-- ========================================

create table if not exists public.md_viajes (

    fo text primary key,

    -- fecha_carga: primer cruce (cuándo entró a la base)
    -- fecha_cruce / cruzado_por: último cruce en que salió como nuevo
    -- cargado_por: quién lo procesó
    fecha_carga timestamptz not null default now(),
    fecha_cruce timestamptz,
    cruzado_por text,
    cargado_por text,

    -- Monitor GRE
    transportista_codigo text,
    transportista_nombre text,

    -- VL06F (resumen del viaje, calculado de sus entregas)
    ruta text,
    -- CANAL MODERNO, RL CMP, RL AS, N/S CHICO, TRASLADO, DEX, LARGA
    -- DISTANCIA... (ver md_reglas_gestion; sin lista fija para que una
    -- gestión nueva no obligue a cambiar la tabla)
    gestion text,
    -- PROCESAR ("Procesar viaje") o SUBIR ("Subir viaje"), ver
    -- md_reglas_gestion
    accion text not null default 'SUBIR'
        check (accion in ('PROCESAR', 'SUBIR')),
    destino text,
    cliente text,
    peso_tn numeric(12, 3),
    cantidad_entregas integer,
    -- Materiales distintos del viaje en el VL06F
    cantidad_skus integer,

    -- NUEVO: cruzado, todavía no procesado (falta Monitor GRE / VL06F)
    -- PENDIENTE: procesado, pero alguna entrega no estaba en el VL06F
    --            (sin peso/destino). Vuelve a salir como nuevo en el
    --            siguiente cruce para completarlo.
    -- PROCESADO: ya tiene todos sus datos (si no se sube, también
    --            vuelve a salir como nuevo en el siguiente cruce)
    -- SUBIDO: ya se subió / procesó desde Cargar Viaje. Es lo único
    --         contra lo que cruza md_viajes_existentes.
    estado text not null default 'NUEVO',

    actualizado_en timestamptz not null default now()

);

-- ========================================
-- STATUS PENDIENTE (data principal)
-- ========================================
-- "Subir viaje" en Cargar Viaje pasa el viaje a estado SUBIDO: desde
-- ahí aparece en la vista Status Pendiente (reemplaza a la hoja STATUS
-- PENDIENTE del Drive), con los mismos status. Arrancan en rojo:
--   status          POR LANZAR  (luego EN PROCESO / CONFIRMADO)
--   status_modulado PENDIENTE   (luego EN PROCESO / CERRADO)
--   status_despacho PENDIENTE
--   status_ut       PENDIENTE
-- Sin lista fija de valores: los irán cambiando Monitor, Despacho y
-- Registro de UT.

alter table public.md_viajes add column if not exists cantidad_skus integer;
alter table public.md_viajes add column if not exists fecha_cruce timestamptz;
alter table public.md_viajes add column if not exists cruzado_por text;
alter table public.md_viajes add column if not exists fecha_subida timestamptz;
alter table public.md_viajes add column if not exists subido_por text;
alter table public.md_viajes add column if not exists fecha_cita date;
alter table public.md_viajes add column if not exists hora_cita time;
alter table public.md_viajes add column if not exists status text;
alter table public.md_viajes add column if not exists status_modulado text;
alter table public.md_viajes add column if not exists status_despacho text;
alter table public.md_viajes add column if not exists fecha_registro_ut timestamptz;
alter table public.md_viajes add column if not exists estadia_ut text;
alter table public.md_viajes add column if not exists status_ut text;

-- ========================================
-- MONITOR
-- ========================================
-- El Monitor llena, sobre los viajes SUBIDO, la FASE, el CANAL SISTEMA
-- (ej. CNL-OUT-84) y el CANAL FÍSICO (ej. "36 - 37"), escribiéndolos en
-- la tabla, y va cambiando el status (la fecha y hora de cita solo las
-- muestra):
-- POR LANZAR → EN PROCESO → CONFIRMADO → CONTABILIZADO → CERRADO.
-- Por ahora una fase por viaje (en el Drive un viaje podía partirse en
-- varias filas, una por fase).

alter table public.md_viajes add column if not exists fase text;
alter table public.md_viajes add column if not exists canal_sistema text;
alter table public.md_viajes add column if not exists canal_fisico text;
-- Último cambio hecho desde el Monitor
alter table public.md_viajes add column if not exists monitor_por text;
alter table public.md_viajes add column if not exists monitor_en timestamptz;

-- ========================================
-- PACKING LIST (Cencosud, Metro, Tottus)
-- ========================================
-- A estos clientes hay que mandarles un packing list. El viaje se sube
-- normal a Status Pendiente, pero queda con pl_pendiente = true hasta
-- que se marca como enviado desde Cargar Viaje ("📦 Pendiente de
-- Packing List"). Qué clientes lo llevan: CLIENTES_CON_PACKING_LIST en
-- cargar-viaje.js.

alter table public.md_viajes add column if not exists pl_pendiente boolean not null default false;
alter table public.md_viajes add column if not exists pl_enviado_en timestamptz;
alter table public.md_viajes add column if not exists pl_enviado_por text;

create index if not exists idx_md_viajes_pl_pendiente
    on public.md_viajes (fecha_subida)
    where pl_pendiente;

-- Status Pendiente muestra los SUBIDO sin filtro de fecha; por defecto
-- solo los pendientes de despacho.
create index if not exists idx_md_viajes_subida
    on public.md_viajes (fecha_subida desc)
    where estado = 'SUBIDO';

create index if not exists idx_md_viajes_despacho
    on public.md_viajes (status_despacho, fecha_subida)
    where estado = 'SUBIDO';

-- Estados con nombre propio para poder sumar PENDIENTE si la tabla ya
-- existía con la primera lista.
alter table public.md_viajes drop constraint if exists md_viajes_estado_check;
alter table public.md_viajes add constraint md_viajes_estado_check
    check (estado in ('NUEVO', 'PENDIENTE', 'PROCESADO', 'SUBIDO'));

create index if not exists idx_md_viajes_fecha_carga
    on public.md_viajes (fecha_carga desc);

create index if not exists idx_md_viajes_gestion_fecha
    on public.md_viajes (gestion, fecha_carga desc);

create index if not exists idx_md_viajes_estado
    on public.md_viajes (estado, fecha_carga desc);

-- "Cruzados sin subir" en Cargar Viaje.
create index if not exists idx_md_viajes_sin_subir
    on public.md_viajes (fecha_cruce desc)
    where estado <> 'SUBIDO';

-- ========================================
-- ENTREGAS (varias por viaje)
-- ========================================

create table if not exists public.md_entregas (

    entrega text primary key,
    fo text not null references public.md_viajes (fo) on delete cascade,

    -- Monitor GRE (la plantilla trae también estas columnas; el archivo
    -- de muestra solo traía Entrega, FO y Transportista)
    serie_guia text,
    correlativo_guia text,
    numero_transporte text,
    placa text,
    brevete_conductor text,
    nombre_conductor text,
    cliente_codigo text,
    cliente_nombre text,

    -- Gestión calculada para esta entrega (ver md_reglas_gestion)
    gestion text,
    accion text not null default 'SUBIR'
        check (accion in ('PROCESAR', 'SUBIR')),

    -- VL06F (iguales en todas las líneas de la entrega)
    documento_modelo text,
    destinatario_codigo text,
    destinatario_nombre text,
    lugar_destinatario text,
    solicitante text,
    organizacion_ventas text,
    ruta text,

    -- VL06F sumado por entrega (Peso total viene en KG)
    peso_kg numeric(12, 3),
    cantidad_lineas integer,
    cantidad_cja numeric(12, 3),
    cantidad_pqt numeric(12, 3),
    cantidad_und numeric(12, 3),

    -- Una entrega del Monitor GRE que todavía no aparece en el VL06F
    -- se guarda igual, con estos campos vacíos (en la muestra: 6 de 250).
    tiene_vl06f boolean not null default false,

    actualizado_en timestamptz not null default now()

);

create index if not exists idx_md_entregas_fo
    on public.md_entregas (fo);

-- ========================================
-- MATERIALES Y RÓTULOS TOTTUS
-- ========================================
-- md_materiales: maestro de materiales (por ahora el rótulo Tottus de
-- la columna "TIENDA TOTTUS" de la MARA de la plantilla F-LAT-058:
-- T.LIMPIEZA / T.HUACHIPA). Se cargó desde la plantilla (1 555
-- materiales); se le pueden sumar columnas (SKU Tottus, EAN...).
-- md_entregas_rotulo: al procesar, el peso de cada entrega de Tottus
-- repartido por rótulo según sus materiales (ver guardarRotulosTottus
-- en cargar-viaje.js).

create table if not exists public.md_materiales (
    material text primary key,
    descripcion text,
    rotulo_tottus text,
    actualizado_en timestamptz not null default now()
);

-- Maestro de Tottus (hoja "Maestro" de la plantilla F-LAT-058, 637
-- materiales): SKU Tottus y conversión a unidades. Lo usa el ASN:
-- unidades = cantidad del VL06F × conversión.
alter table public.md_materiales add column if not exists sku_tottus text;
alter table public.md_materiales add column if not exists conversion_tottus numeric(12, 3);

create table if not exists public.md_entregas_rotulo (
    entrega text not null references public.md_entregas (entrega) on delete cascade,
    fo text not null,
    rotulo text not null,
    peso_kg numeric(12, 3) not null default 0,
    cantidad_lineas integer not null default 0,
    actualizado_en timestamptz not null default now(),
    primary key (entrega, rotulo)
);

create index if not exists idx_md_entregas_rotulo_fo on public.md_entregas_rotulo (fo);

