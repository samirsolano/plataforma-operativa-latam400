-- archivo, al volver a correrlo ajusta esas tablas (ver "AJUSTES A LA
-- PRIMERA VERSIÓN" al final) sin perder datos.
-- ========================================
-- De dónde sale cada dato (archivos de SAP):
--   Monitor GRE: Entrega, Orden de flete (FO), Código y Nombre
--     Transportista. Una fila por entrega; un viaje (FO) tiene varias
--     entregas (en la muestra, hasta 34) y un solo transportista.
--   VL06F (Programaciones): una fila por MATERIAL de cada entrega
--     (Entrega, Material, Cantidad, Peso total en KG, Destinatario,
--     Lugar, Solicitante, Organización ventas, Ruta...). Destinatario,
--     Lugar, Ruta, etc. son siempre los mismos dentro de una entrega.
--
-- Estructura:
--   md_viajes   → una fila por viaje (FO). Es la "Base de Datos" contra
--                 la que se hace el Cruce de Viajes.
--   md_entregas → una fila por entrega de cada viaje, con los datos del
--                 VL06F ya SUMADOS por entrega (peso, cantidades).
--   md_cruces   → historial de cada vez que se pegan viajes (reemplaza
--                 el "Ver último cruce" guardado en el navegador).
--   md_reglas_gestion → reglas para decidir la gestión de cada viaje
--                 (copiadas de la hoja DATADRIVE / tabla ClientesGestion
--                 de la plantilla F-LAT-055).
--
-- PENSADO PARA CRECER:
--   * El detalle por material del VL06F NO se guarda (en la muestra
--     son ~45 líneas por viaje: a 200 viajes/día serían ~3 millones de
--     filas al año). Se guarda sumado por entrega, que es lo que usan
--     las pantallas. Si algún día hace falta el detalle por material,
--     se agrega una tabla aparte.
--   * El cruce NO descarga la tabla: la función md_viajes_existentes
--     recibe solo los viajes pegados y devuelve cuáles ya existen
--     (usa la llave primaria, es inmediato aunque haya millones).
--   * Índices por fecha de carga, gestión y estado: por ahí filtran
--     Base de Datos y Reportes (siempre por rango de fechas y
--     paginado, nunca la tabla completa).

-- ========================================
-- REGLAS DE GESTIÓN
-- ========================================
-- La gestión no viene en ningún archivo de SAP: la plantilla
-- F-LAT-055 la calcula con la consulta "Consulta1" (Power Query) a
-- partir de esta tabla de reglas. La plataforma usa la MISMA lógica,
-- para cada entrega, en este orden de prioridad:
--
--   1. Regla CLIENTE: el nombre del cliente destinatario es igual a
--      "cliente" → esa gestión. Si "procesar" es false, la entrega NO
--      se sube al Drive (en la plantilla se eliminaba; acá se marca).
--   2. Destino que empieza con "LIMA - LIMA" o "CALLAO":
--        Organización ventas 1012        → RL AS
--        Organización ventas 1010 / 1011 → RL CMP
--   3. Regla TIPO_DESTINO "LIMA PROVINCIA": destino que empieza con
--      "LIMA" pero no es "LIMA - LIMA" (Cañete, Huaura, Barranca...).
--   4. Regla DESTINO: el destino EMPIEZA con "destino" (ej. "ÁNCASH"
--      cubre "ÁNCASH - HUARAZ").
--   5. Si nada coincide → LARGA DISTANCIA.
--
-- La gestión del viaje es la de su primera entrega. Los textos se
-- comparan "limpios": en mayúsculas, sin espacios dobles ni al
-- inicio/fin (igual que LimpiarTexto en la plantilla), por eso acá se
-- guardan ya así.

create table if not exists public.md_reglas_gestion (

    id bigint generated by default as identity primary key,
    tipo_regla text not null
        check (tipo_regla in ('CLIENTE', 'DESTINO', 'TIPO_DESTINO')),
    cliente text,
    destino text,
    gestion text not null,
    procesar boolean not null default true,
    actualizado_en timestamptz not null default now(),

    unique nulls not distinct (tipo_regla, cliente, destino)

);

