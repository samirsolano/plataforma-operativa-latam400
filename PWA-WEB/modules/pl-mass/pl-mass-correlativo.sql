-- Registra el PL de un viaje. Los LPN NUNCA se borran ni se reusan:
--   - Viaje sin PL: reserva un bloque nuevo de correlativos, arma
--     cada LPN = '500000' + O/C + últimos 4 dígitos del correlativo
--     (después de 9999 sigue 0000) y lo guarda en pl_mass_lpn.
--   - Viaje que ya tiene PL: error, salvo p_reemplazar = true; en ese
--     caso sus LPN vigentes quedan anulados (siguen registrados y
--     bloqueados) y el viaje recibe un bloque NUEVO.
-- Todo o nada: si algún LPN ya existe (vigente o anulado), no se
-- guarda nada y el contador no se mueve. Devuelve las filas vigentes
-- del viaje en el orden del PL.
--
-- p_filas: [{oc, pedido, local, sku, material, cantidad, lote, fecha (yyyy-mm-dd), hu}, ...]
drop function if exists public.pl_mass_registrar_pl(text, jsonb, text);

create or replace function public.pl_mass_registrar_pl(
    p_fo text,
    p_filas jsonb,
    p_usuario text default null,
    p_reemplazar boolean default false
)
returns setof public.pl_mass_lpn
language plpgsql
security definer
set search_path = public
as $$
declare
    v_fo text := btrim(coalesce(p_fo, ''));
    v_cantidad int;
    v_inicio bigint;
    v_choque record;
begin
    if v_fo = '' then
        raise exception 'Falta el viaje (F.O).';
    end if;

    if p_filas is null or jsonb_typeof(p_filas) <> 'array' or jsonb_array_length(p_filas) = 0 then
        raise exception 'El PL no tiene filas.';
    end if;

    if exists (select 1 from jsonb_array_elements(p_filas) f where coalesce(btrim(f->>'oc'), '') = '') then
        raise exception 'Hay filas sin O/C.';
    end if;

    v_cantidad := jsonb_array_length(p_filas);

    -- Bloquea el contador: las asignaciones se hacen de una en una.
    perform 1 from public.pl_mass_correlativo where id = 1 for update;

    if exists (select 1 from public.pl_mass_lpn where fo = v_fo and not anulado) then

        if not coalesce(p_reemplazar, false) then
            raise exception 'El viaje % ya tiene PL generado. Descárgalo o usa "Anular y regenerar".', v_fo;
        end if;

        update public.pl_mass_lpn
           set anulado = true, anulado_por = p_usuario, anulado_at = now()
         where fo = v_fo and not anulado;

    end if;

    update public.pl_mass_correlativo
       set siguiente = siguiente + v_cantidad
     where id = 1
    returning siguiente - v_cantidad into v_inicio;

    select l.lpn, l.fo, l.anulado into v_choque
      from jsonb_array_elements(p_filas) with ordinality as f(fila, n)
      join public.pl_mass_lpn l
        on l.lpn = '500000' || btrim(f.fila->>'oc') || lpad(((v_inicio + f.n - 1) % 10000)::text, 4, '0')
     limit 1;

    if found then
        raise exception 'El LPN % ya fue generado antes (viaje %, %). No se guardó nada.', v_choque.lpn, v_choque.fo,
            case when v_choque.anulado then 'anulado' else 'vigente' end;
    end if;

    insert into public.pl_mass_lpn
        (lpn, fo, orden, correlativo, oc, pedido, local_destino, sku, material, cantidad, lote, fecha_vto, hu, generado_por)
    select
        '500000' || btrim(f.fila->>'oc') || lpad(((v_inicio + f.n - 1) % 10000)::text, 4, '0'),
        v_fo,
        f.n,
        v_inicio + f.n - 1,
        btrim(f.fila->>'oc'),
        f.fila->>'pedido',
        f.fila->>'local',
        f.fila->>'sku',
        f.fila->>'material',
        nullif(f.fila->>'cantidad', '')::numeric,
        f.fila->>'lote',
        nullif(f.fila->>'fecha', '')::date,
        f.fila->>'hu',
        p_usuario
    from jsonb_array_elements(p_filas) with ordinality as f(fila, n);

    insert into public.pl_mass_pl (fo, correlativo_inicio, cantidad, generado_por, updated_at)
    values (v_fo, v_inicio, v_cantidad, p_usuario, now())
    on conflict (fo) do update
       set correlativo_inicio = excluded.correlativo_inicio,
           cantidad = excluded.cantidad,
           generado_por = excluded.generado_por,
           updated_at = now();

    return query select * from public.pl_mass_lpn where fo = v_fo and not anulado order by orden;
end;
$$;

revoke all on function public.pl_mass_registrar_pl(text, jsonb, text, boolean) from public;
grant execute on function public.pl_mass_registrar_pl(text, jsonb, text, boolean) to anon, authenticated;

