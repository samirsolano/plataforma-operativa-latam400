-- ========================================
-- MÓDULO "PL MASS" — LPN y correlativo. Corre esto UNA VEZ en el
-- SQL Editor de WMS Dashboard (iaitqquphjohgsmelhcj), después de
-- mara-mass.sql.
-- ========================================
-- LPN = "500000" + O/C + correlativo de 4 dígitos.
--
-- El correlativo es POR O/C y NO lo escribe el usuario:
--   - Una O/C nueva empieza en 0001.
--   - Si la O/C vuelve a salir (en otro PL), sigue desde su último
--     correlativo (contando también los LPN anulados).
--   - Un LPN nunca se repite: lpn es único en pl_mass_lpn.
--
-- pl_mass_lpn: registro de TODOS los LPN generados (nunca se borran).
-- pl_mass_pl: resumen por viaje (F.O) del PL vigente.
-- pl_mass_oc_siguiente: vista con el siguiente correlativo de cada O/C.
--
-- La app (clave anon) solo puede LEER; el único camino para generar
-- LPN es pl_mass_registrar_pl() (security definer), todo o nada.

create table if not exists public.pl_mass_pl (
    fo text primary key,
    cantidad int not null check (cantidad > 0),
    generado_por text,
    updated_at timestamptz not null default now()
);

create table if not exists public.pl_mass_lpn (
    id bigint generated by default as identity primary key,
    lpn text not null unique,
    fo text not null,
    orden int not null,
    correlativo bigint not null,
    oc text not null,
    pedido text,
    local_destino text,
    sku text,
    material text,
    cantidad numeric,
    lote text,
    fecha_vto date,
    hu text,
    generado_por text,
    created_at timestamptz not null default now(),
    anulado boolean not null default false,
    anulado_por text,
    anulado_at timestamptz,
    -- false = bloquea el LPN (no se repite) pero no cuenta para el
    -- correlativo de su O/C (PL históricos cargados a mano).
    cuenta_correlativo boolean not null default true
);

create index if not exists pl_mass_lpn_fo_idx on public.pl_mass_lpn (fo, orden);
create index if not exists pl_mass_lpn_oc_idx on public.pl_mass_lpn (oc, correlativo);

alter table public.pl_mass_pl enable row level security;
alter table public.pl_mass_lpn enable row level security;

drop policy if exists "pl_mass_pl_select_anon" on public.pl_mass_pl;
drop policy if exists "pl_mass_lpn_select_anon" on public.pl_mass_lpn;

create policy "pl_mass_pl_select_anon" on public.pl_mass_pl for select to anon using (true);
create policy "pl_mass_lpn_select_anon" on public.pl_mass_lpn for select to anon using (true);

create or replace view public.pl_mass_oc_siguiente
with (security_invoker = true) as
select oc, max(correlativo) + 1 as siguiente, count(*) as lpn_generados
  from public.pl_mass_lpn
 where cuenta_correlativo
 group by oc;

grant select on public.pl_mass_oc_siguiente to anon, authenticated;

-- Registra el PL de un viaje.
--   - Viaje sin PL: numera cada fila con el correlativo de su O/C y
--     guarda los LPN.
--   - Viaje con PL: error, salvo p_reemplazar = true; en ese caso sus
--     LPN vigentes quedan anulados (siguen registrados y bloqueados) y
--     se generan LPN nuevos que continúan el correlativo de cada O/C.
-- Todo o nada: si algún LPN ya existe o una O/C pasa de 9999, no se
-- guarda nada. Devuelve las filas vigentes del viaje en orden.
--
-- p_filas: [{oc, pedido, local, sku, material, cantidad, lote, fecha (yyyy-mm-dd), hu}, ...]
create or replace function public.pl_mass_registrar_pl(
    p_fo text,
    p_filas jsonb,
    p_usuario text default null,
    p_reemplazar boolean default false
)
returns setof public.pl_mass_lpn
language plpgsql
security definer
set search_path = public
as $$
declare
    v_fo text := btrim(coalesce(p_fo, ''));
    v_choque record;
begin
    if v_fo = '' then
        raise exception 'Falta el viaje (F.O).';
    end if;

    if p_filas is null or jsonb_typeof(p_filas) <> 'array' or jsonb_array_length(p_filas) = 0 then
        raise exception 'El PL no tiene filas.';
    end if;

    if exists (select 1 from jsonb_array_elements(p_filas) f where coalesce(btrim(f->>'oc'), '') !~ '^\d+$') then
        raise exception 'Hay filas sin O/C o con O/C no numérica.';
    end if;

    -- Un solo registro a la vez (evita que dos personas tomen el mismo correlativo).
    perform pg_advisory_xact_lock(hashtext('pl_mass_registrar_pl'));

    if exists (select 1 from public.pl_mass_lpn where fo = v_fo and not anulado) then

        if not coalesce(p_reemplazar, false) then
            raise exception 'El viaje % ya tiene PL generado. Descárgalo o usa "Anular y regenerar".', v_fo;
        end if;

        update public.pl_mass_lpn
           set anulado = true, anulado_por = p_usuario, anulado_at = now()
         where fo = v_fo and not anulado;

    end if;

    drop table if exists _pl_nuevo;
    create temp table _pl_nuevo on commit drop as
    with filas as (
        select f.fila, f.n, btrim(f.fila->>'oc') as oc
          from jsonb_array_elements(p_filas) with ordinality as f(fila, n)
    ),
    base as (
        select oc, coalesce(max(correlativo), 0) as ultimo
          from public.pl_mass_lpn
         where cuenta_correlativo
         group by oc
    )
    select filas.*,
           coalesce(base.ultimo, 0) + row_number() over (partition by filas.oc order by filas.n) as correlativo
      from filas
      left join base on base.oc = filas.oc;

    if exists (select 1 from _pl_nuevo where correlativo > 9999) then
        raise exception 'La O/C % pasaría de 9999 LPN (el correlativo es de 4 dígitos). No se guardó nada.',
            (select oc from _pl_nuevo where correlativo > 9999 limit 1);
    end if;

    select l.lpn, l.fo, l.anulado into v_choque
      from _pl_nuevo t
      join public.pl_mass_lpn l on l.lpn = '500000' || t.oc || lpad(t.correlativo::text, 4, '0')
     limit 1;

    if found then
        raise exception 'El LPN % ya fue generado antes (viaje %, %). No se guardó nada.', v_choque.lpn, v_choque.fo,
            case when v_choque.anulado then 'anulado' else 'vigente' end;
    end if;

    insert into public.pl_mass_lpn
        (lpn, fo, orden, correlativo, oc, pedido, local_destino, sku, material, cantidad, lote, fecha_vto, hu, generado_por)
    select
        '500000' || t.oc || lpad(t.correlativo::text, 4, '0'),
        v_fo,
        t.n,
        t.correlativo,
        t.oc,
        t.fila->>'pedido',
        t.fila->>'local',
        t.fila->>'sku',
        t.fila->>'material',
        nullif(t.fila->>'cantidad', '')::numeric,
        t.fila->>'lote',
        nullif(t.fila->>'fecha', '')::date,
        t.fila->>'hu',
        p_usuario
    from _pl_nuevo t;

    insert into public.pl_mass_pl (fo, cantidad, generado_por, updated_at)
    values (v_fo, jsonb_array_length(p_filas), p_usuario, now())
    on conflict (fo) do update
       set cantidad = excluded.cantidad,
           generado_por = excluded.generado_por,
           updated_at = now();

    return query select * from public.pl_mass_lpn where fo = v_fo and not anulado order by orden;
end;
$$;

revoke all on function public.pl_mass_registrar_pl(text, jsonb, text, boolean) from public;
grant execute on function public.pl_mass_registrar_pl(text, jsonb, text, boolean) to anon, authenticated;

