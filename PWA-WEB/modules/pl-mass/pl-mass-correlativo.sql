-- ========================================
-- LPN = "500000" + O/C + correlativo de 4 dígitos. El correlativo NO
-- lo escribe el usuario: lo asigna la base con
-- pl_mass_asignar_correlativo(), que reserva un bloque de números de
-- forma atómica (dos personas generando a la vez nunca reciben el
-- mismo número).
--
-- pl_mass_correlativo: una sola fila con el siguiente número libre.
-- pl_mass_pl: último bloque que recibió cada viaje (F.O).
--
-- pl_mass_lpn: registro de TODOS los LPN generados (lpn único: la base
-- no deja que un LPN se repita entre viajes).
--
-- La app (clave anon) solo puede LEER estas tablas; el único camino
-- para mover el contador y guardar LPN es pl_mass_registrar_pl()
-- (security definer), que hace todo en una sola transacción.

create table if not exists public.pl_mass_correlativo (
    id int primary key default 1 check (id = 1),
    siguiente bigint not null
);

