-- ========================================
-- MÓDULO "PL MASS" — tabla "mara_mass". Corre esto UNA VEZ en el
-- SQL Editor del proyecto Supabase WMS Dashboard
-- (iaitqquphjohgsmelhcj), que es el que usa toda la plataforma.
-- ========================================
-- Maestro de materiales propio del PL MASS (CD MASS CALLAO), copiado
-- de la hoja "MARA" de la plantilla
-- "Plantilla_Carga_LPN_Supermercados ... .xlsm". Es OTRA MARA,
-- separada de mara_productos (Toma de Lote Supermercados).
--
-- sku = "Material S4H" (el "Material" de la VL06F y el "Producto"
-- de la Fase). codigo_spsa es el SKU que sale en el PL.
-- La carga inicial de datos está en mara-mass-datos.sql; después se
-- actualiza desde el mismo módulo (botón "Importar MARA").

create table if not exists public.mara_mass (

    id bigint generated by default as identity primary key,

    sku text not null unique,
    material_ewm text,
    descripcion text,
    codigo_spsa text,
    unidad_venta text,
    unidad_base text,
    conversion numeric,
    ean14 text,
    ean13 text,
    ctd_por_palet numeric,

    archivo_origen text,
    cargado_por text,
    created_at timestamptz not null default now()

);

-- ========================================
-- RLS — mismo criterio que el resto del proyecto: la app usa la
-- clave pública (anon) del cliente para todo, sin login propio de
-- Supabase, así que las políticas quedan abiertas a "anon".
-- ========================================

alter table public.mara_mass enable row level security;

drop policy if exists "mara_mass_select_anon" on public.mara_mass;
drop policy if exists "mara_mass_insert_anon" on public.mara_mass;
drop policy if exists "mara_mass_update_anon" on public.mara_mass;
drop policy if exists "mara_mass_delete_anon" on public.mara_mass;

create policy "mara_mass_select_anon" on public.mara_mass for select to anon using (true);
create policy "mara_mass_insert_anon" on public.mara_mass for insert to anon with check (true);
create policy "mara_mass_update_anon" on public.mara_mass for update to anon using (true) with check (true);
create policy "mara_mass_delete_anon" on public.mara_mass for delete to anon using (true);
